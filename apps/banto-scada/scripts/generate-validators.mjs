// Generates the JSON Schema validators as standalone ES modules.
//
// The Tauri release build runs under a CSP without 'unsafe-eval', so Ajv may
// not compile schemas in the browser (`new Function` throws EvalError). The
// product code imports these pre-generated functions instead. Each module keeps
// the Ajv options and referenced schemas the product code used before, so
// error objects and counts stay the same.
//
//   pnpm generate:validators              writes src/lib/generated/validators/
//   src/lib/generated-validators.test.ts  fails when the files are stale
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

const repo = new URL("../../../", import.meta.url);
const app = new URL("../", import.meta.url);
export const OUTPUT_DIR = new URL("src/lib/generated/validators/", app);

const crate = (path) => new URL(`crates/${path}`, repo);
const SCHEMA = {
  catalogView: crate("scada-runtime/schema/catalog-view.schema.json"),
  readSlotView: crate("scada-runtime/schema/read-slot-view.schema.json"),
  runtimeView: crate("scada-runtime/schema/runtime-view.schema.json"),
  readDisplayUpdate: crate(
    "scada-runtime/schema/read-display-update.schema.json",
  ),
  history: crate("scada-historian/schema/history-contract.schema.json"),
  project: crate("scada-model/schema/project.schema.json"),
  legacyProject: crate("scada-model/schema/legacy.project.schema.json"),
  trend: crate("scada-model/schema/trend-definition.schema.json"),
  plan: crate("scada-model/schema/recording-plan.schema.json"),
  management: crate("scada-model/schema/recording-management.schema.json"),
  operations: crate("scada-model/schema/recording-operations.schema.json"),
  admission: crate("scada-model/schema/recording-admission.schema.json"),
  wire: crate("scada-model/schema/recording-wire.schema.json"),
  historyContext: new URL("src/lib/history/history-context.schema.json", app),
};

/**
 * One Ajv instance (with the product's options) per generated module.
 * `refs` are only added; `exports` are compiled in order and exported by name.
 */
export const MODULES = {
  // catalog-session.ts
  "catalog-view": {
    options: { strictNumbers: true },
    refs: [],
    exports: { validateCatalogView: SCHEMA.catalogView },
  },
  // history-contract.ts
  "history-contract": {
    options: { strictNumbers: false, allowUnionTypes: true },
    refs: [],
    exports: { validateHistoryContract: SCHEMA.history },
  },
  // history/workspace-model.ts
  "history-context": {
    options: { strictNumbers: true },
    refs: [SCHEMA.history],
    exports: { validateHistoryContext: SCHEMA.historyContext },
  },
  // project.ts
  project: {
    options: { allErrors: true, strictNumbers: true, allowUnionTypes: true },
    refs: [SCHEMA.history, SCHEMA.plan, SCHEMA.trend],
    exports: {
      validateProject: SCHEMA.project,
      validateLegacyProject: SCHEMA.legacyProject,
    },
  },
  // read-presentation.ts
  "read-display-update": {
    options: { allErrors: true, strictNumbers: true },
    refs: [SCHEMA.readSlotView, SCHEMA.runtimeView],
    exports: { validateReadDisplayUpdate: SCHEMA.readDisplayUpdate },
  },
  // read-slot-session.ts
  "read-slot-view": {
    options: { allErrors: true, strictNumbers: true },
    refs: [],
    exports: { validateReadSlotView: SCHEMA.readSlotView },
  },
  // recording-{plan,management,operations,admission,wire}*.ts all used
  // { strictNumbers: true } with the schemas they reference. One instance
  // shares the referenced validators; an unreferenced schema changes nothing.
  recording: {
    options: { strictNumbers: true },
    refs: [SCHEMA.history],
    exports: {
      validateRecordingPlan: SCHEMA.plan,
      validateRecordingManagement: SCHEMA.management,
      validateRecordingOperations: SCHEMA.operations,
      validateRecordingAdmission: SCHEMA.admission,
      validateRecordingWire: SCHEMA.wire,
    },
  },
  // trend-definitions.ts
  "trend-definitions": {
    options: { strictNumbers: true, allowUnionTypes: true },
    refs: [SCHEMA.history],
    exports: { validateTrendDefinitions: SCHEMA.trend },
  },
};

const HEADER =
  "// Generated by scripts/generate-validators.mjs. Do not edit; run `pnpm generate:validators`.\n";
const RUNTIME = "ajv-runtime";
const RUNTIME_REQUIRE =
  /require\("ajv\/dist\/runtime\/([a-z0-9_]+)"\)\.default/g;

const readJson = (url) => JSON.parse(readFileSync(url, "utf8"));

/** Ajv's ESM output still `require`s its runtime helpers; route them through one ES module. */
function toEsm(code, runtimeNames) {
  const used = new Set();
  const body = code
    .replace(/^"use strict";\n?/, "")
    .replace(RUNTIME_REQUIRE, (_, name) => {
      used.add(name);
      runtimeNames.add(name);
      return `ajvRuntime_${name}`;
    });
  if (/\brequire\(/.test(body))
    throw new Error("unexpected require() in Ajv standalone output");
  const imports = [...used]
    .sort()
    .map(
      (name) =>
        `import { ${name} as ajvRuntime_${name} } from "./${RUNTIME}.js";\n`,
    )
    .join("");
  return `${HEADER}${imports}${body}\n`;
}

/** Returns every generated file as `{ [fileName]: content }` (LF line endings). */
export function generateValidators() {
  const files = {};
  const runtimeNames = new Set();
  for (const [module, entry] of Object.entries(MODULES)) {
    const ajv = new Ajv2020({
      ...entry.options,
      logger: false,
      code: { source: true, esm: true, lines: true },
    });
    for (const ref of entry.refs) ajv.addSchema(readJson(ref));
    const keys = {};
    for (const [name, url] of Object.entries(entry.exports)) {
      const schema = readJson(url);
      keys[name] = schema.$id ?? name;
      ajv.addSchema(schema, schema.$id ? undefined : name);
    }
    files[`${module}.js`] = toEsm(standaloneCode(ajv, keys), runtimeNames);
    files[`${module}.d.ts`] =
      `${HEADER}import type { ValidateFunction } from "ajv";\n` +
      Object.keys(entry.exports)
        .map((name) => `export declare const ${name}: ValidateFunction;\n`)
        .join("");
  }
  const names = [...runtimeNames].sort();
  files[`${RUNTIME}.js`] =
    HEADER +
    names
      .map(
        (name) =>
          `import * as ${name}Module from "ajv/dist/runtime/${name}.js";\n`,
      )
      .join("") +
    "// Node returns module.exports as the CommonJS default; bundlers return exports.default.\n" +
    'const unwrap = (module) => (typeof module.default === "function" ? module.default : module.default.default);\n' +
    names
      .map((name) => `export const ${name} = unwrap(${name}Module);\n`)
      .join("");
  files[`${RUNTIME}.d.ts`] =
    HEADER +
    names
      .map(
        (name) =>
          `export declare const ${name}: (...args: never[]) => unknown;\n`,
      )
      .join("");
  return files;
}

function write() {
  const files = generateValidators();
  mkdirSync(OUTPUT_DIR, { recursive: true });
  for (const name of readdirSync(OUTPUT_DIR))
    if (!(name in files)) rmSync(new URL(name, OUTPUT_DIR));
  for (const [name, content] of Object.entries(files))
    writeFileSync(new URL(name, OUTPUT_DIR), content);
  console.log(
    `generated ${Object.keys(files).length} files in ${fileURLToPath(OUTPUT_DIR)}`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  write();
